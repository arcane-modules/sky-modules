import type { AnyTraitClass, CheckTrait, IsSame, TraitApiKey } from './trait'

/** Marker for incompatible members; `compose` refuses such lists at compile time. */
export interface ShapeConflict<K extends PropertyKey> {
    readonly __conflict: K
}

/** Merges two member maps. Same key with different types becomes `ShapeConflict`. */
export type MergeShapes<A, B> = {
    [K in keyof A | keyof B]: K extends keyof A
        ? K extends keyof B
            ? IsSame<A[K], B[K]> extends true
                ? A[K]
                : ShapeConflict<K>
            : A[K]
        : K extends keyof B
          ? B[K]
          : never
}

type TraitShape<T> = T extends new (...args: never[]) => infer I ? Omit<I, TraitApiKey> : never

type ListShape<L extends readonly AnyTraitClass[]> = L extends readonly [
    infer H extends AnyTraitClass,
    ...infer R extends AnyTraitClass[],
]
    ? MergeShapes<TraitShape<H>, ListShape<R>>
    : object

type HasConflict<S> = true extends {
    [K in keyof S]: S[K] extends ShapeConflict<PropertyKey> ? true : false
}[keyof S]
    ? true
    : false

type CheckedTraits<L extends readonly AnyTraitClass[]> =
    HasConflict<ListShape<L>> extends true ? never : { readonly [K in keyof L]: CheckTrait<L[K]> }

/** Trait API generated by `compose`; `set` and the constructor are written by the user. */
export interface ComposedApi {
    copy(other: this): this
    clone(): this
}

export type ComposedInstance<L extends readonly AnyTraitClass[]> = ListShape<L> & ComposedApi

export interface ComposedClass<L extends readonly AnyTraitClass[]> {
    new (): ComposedInstance<L>
    readonly prototype: ComposedInstance<L>
}

interface RuntimeTraitPrototype {
    copy(this: object, other: object): object
}

interface RuntimeTrait {
    new (): object
    readonly name: string
    readonly prototype: RuntimeTraitPrototype
}

const RESERVED_KEYS: ReadonlySet<PropertyKey> = new Set<PropertyKey>(['constructor', 'set', 'copy', 'clone'])

function uniqueTraits(traits: readonly RuntimeTrait[]): RuntimeTrait[] {
    return [...new Set(traits)]
}

/** Members of a trait along its prototype chain; the nearest definition wins. */
function traitMembers(trait: RuntimeTrait): Map<PropertyKey, PropertyDescriptor> {
    const members = new Map<PropertyKey, PropertyDescriptor>()

    for (
        let proto: object | null = trait.prototype;
        proto !== null && proto !== Object.prototype;
        proto = Object.getPrototypeOf(proto) as object | null
    ) {
        for (const key of Reflect.ownKeys(proto)) {
            if (RESERVED_KEYS.has(key) || members.has(key)) continue

            const descriptor = Object.getOwnPropertyDescriptor(proto, key)
            if (descriptor !== undefined) members.set(key, descriptor)
        }
    }

    return members
}

function isSameDescriptor(a: PropertyDescriptor, b: PropertyDescriptor): boolean {
    return a.value === b.value && a.get === b.get && a.set === b.set
}

function collectMembers(traits: readonly RuntimeTrait[]): Map<PropertyKey, PropertyDescriptor> {
    const owners = new Map<PropertyKey, string>()
    const members = new Map<PropertyKey, PropertyDescriptor>()

    for (const trait of traits) {
        for (const [key, descriptor] of traitMembers(trait)) {
            const previous = members.get(key)
            if (previous !== undefined) {
                if (!isSameDescriptor(previous, descriptor)) {
                    throw new Error(
                        `compose: member "${String(key)}" is defined by both "${owners.get(key)}" and "${trait.name}"`
                    )
                }
                continue
            }

            owners.set(key, trait.name)
            members.set(key, descriptor)
        }
    }

    return members
}

/**
 * Builds a base class whose prototype holds the members of all traits (once),
 * plus generated `copy` (runs every trait `copy`) and `clone`.
 * The base constructor allocates nested state of every trait via `new Trait()`;
 * the subclass defines its own constructor and `set`.
 */
export function compose<const L extends readonly AnyTraitClass[]>(...traits: CheckedTraits<L>): ComposedClass<L> {
    const list = uniqueTraits(traits as unknown as readonly RuntimeTrait[])
    const copies = list.map((trait) => trait.prototype.copy)

    class Composed {
        constructor() {
            for (const trait of list) Object.assign(this, new trait())
        }

        copy(other: object): this {
            for (const copy of copies) copy.call(this, other)
            return this
        }

        clone(): this {
            return new (this.constructor as new () => this)().copy(this)
        }
    }

    for (const [key, descriptor] of collectMembers(list)) {
        Object.defineProperty(Composed.prototype, key, descriptor)
    }

    return Composed as unknown as ComposedClass<L>
}
